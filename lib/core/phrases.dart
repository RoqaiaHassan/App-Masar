  /// يختار عبارة من [list] حسب [seed]: نفس الـ seed = نفس العبارة دائماً،
  /// وأي تغيير في الـ seed (تقدم جديد، يوم جديد...) قد يعطي عبارة مختلفة.
  static String pick(List<String> list, String seed) {
    var h = 7;
    for (final unit in seed.codeUnits) {
      h = (h * 31 + unit) & 0x7fffffff;
    }
    return list[h % list.length];
  }
